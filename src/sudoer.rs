//! Права root: один пароль на сессию вместо пароля на каждую команду.
//!
//! sudo помнит введённый пароль несколько минут и привязывает эту память к
//! терминалу. Пульт этим и пользуется: спрашивает пароль один раз, а дальше
//! запускает всё с `-n` — молча и без риска повиснуть на невидимом запросе.
//!
//! Повиснуть — не выдумка: экран держит клавиатуру себе, и sudo, спросивший
//! пароль из подпроцесса, ждёт ответа, которого никто не даст.

use std::process::{Command, Stdio};

/// Признак «спрашивать пароль некому»: выставляется экраном подпроцессам.
pub const NOASK: &str = "NETPULT_NOASK";

pub fn noask() -> bool {
    std::env::var(NOASK).is_ok()
}

/// Помнит ли sudo пароль прямо сейчас.
pub fn have_ticket() -> bool {
    Command::new("sudo")
        .args(["-n", "true"])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

/// Заготовка команды sudo. Там, где спросить пароль некому, добавляем `-n`:
/// пусть лучше сразу скажет «нужен пароль», чем зависнет молча.
pub fn command() -> Command {
    let mut c = Command::new("sudo");
    if noask() {
        c.arg("-n");
    }
    c
}

/// Спросить пароль сейчас, ничего больше не делая. Терминал при этом должен
/// принадлежать нам — экран уступает его на время этого вызова.
pub fn ask() -> Result<(), String> {
    let ok = Command::new("sudo")
        .args(["-v"])
        .status()
        .map_err(|e| format!("sudo не запустился: {e}"))?
        .success();
    if ok {
        Ok(())
    } else {
        Err("пароль не принят".into())
    }
}

/// Одна и та же фраза на всех путях: экран узнаёт по ней, что дело встало
/// именно из-за пароля, и предлагает его ввести.
pub const NEED_PASSWORD: &str = "нужен пароль администратора";

/// Можно ли прямо сейчас выполнить что-то от root, никого не спрашивая.
pub fn ready() -> Result<(), String> {
    if !noask() || have_ticket() {
        Ok(())
    } else {
        Err(NEED_PASSWORD.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn без_запрета_спрашивать_пароль_всё_разрешено() {
        // Переменную в тестах не выставляем: обычный запуск — интерактивный,
        // и предварительная проверка не должна мешать.
        if !noask() {
            assert!(ready().is_ok());
        }
    }

    #[test]
    fn фраза_про_пароль_одна_на_всех() {
        assert!(NEED_PASSWORD.contains("пароль"));
    }
}
